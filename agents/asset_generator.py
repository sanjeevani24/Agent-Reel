"""Asset Generator (Milestone B): original placeholder visuals + a truthful asset manifest.

Only the per-shot PNG cards are actually created here. Voice-over, subtitles and music are
recorded as 'planned' / 'omitted' (Milestone C) - never as generated.
"""
from __future__ import annotations

import colorsys
import csv
import shutil
import textwrap
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont
from pydantic import BaseModel

from core.brief import Brief
from core.schemas import AssetManifest, AssetRecord, StoryboardOutput, VideoSpec
from core.validators import limit_caption

FONT_CANDIDATES = ["/System/Library/Fonts/Supplemental/Arial Bold.ttf", "/System/Library/Fonts/Helvetica.ttc",
                   "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"]
SOURCE = "programmatically generated by agents/asset_generator.py (Pillow)"
LICENCE = "original work created by this project; no third-party material"
CSV_FIELDS = ["asset_path", "source", "licence_status", "intended_use", "asset_id", "kind", "status"]


class AssetGenInput(BaseModel):
    brief: Brief
    storyboard: StoryboardOutput
    spec: VideoSpec
    root: str
    seed: int = 42


def _font(size: int):
    for path in FONT_CANDIDATES:
        try:
            return ImageFont.truetype(path, size)
        except OSError:
            continue
    return ImageFont.load_default(size=size)


def _gradient(width: int, height: int, hue: float) -> Image.Image:
    top = tuple(int(c * 255) for c in colorsys.hsv_to_rgb(hue, 0.55, 0.30))
    bottom = tuple(int(c * 255) for c in colorsys.hsv_to_rgb((hue + 0.12) % 1, 0.65, 0.65))
    img = Image.new("RGB", (width, height))
    draw = ImageDraw.Draw(img)
    for y in range(height):
        t = y / (height - 1)
        draw.line([(0, y), (width, y)], fill=tuple(int(a + (b - a) * t) for a, b in zip(top, bottom)))
    return img


def _wrap(draw, text: str, font, max_w: int) -> list[str]:
    lines, cur = [], ""
    for word in text.split():
        trial = f"{cur} {word}".strip()
        if draw.textlength(trial, font=font) <= max_w or not cur:
            cur = trial
        else:
            lines.append(cur)
            cur = word
    return lines + ([cur] if cur else [])


def render_card(path: Path, label: str, text: str, hue: float, spec: VideoSpec) -> None:
    """Gradient card with the shot caption centred inside the safe zone."""
    img = _gradient(spec.width, spec.height, hue)
    draw = ImageDraw.Draw(img)
    area_top, area_bottom, margin = spec.safe_top_px + 60, spec.height - spec.safe_bottom_px - 60, 90
    for size in range(88, 35, -8):
        font = _font(size)
        lines = _wrap(draw, text or " ", font, spec.width - 2 * margin)
        line_h = int(size * 1.25)
        if len(lines) * line_h <= area_bottom - area_top:
            break
    y = area_top + ((area_bottom - area_top) - len(lines) * line_h) // 2
    for line in lines:
        w = draw.textlength(line, font=font)
        draw.text(((spec.width - w) / 2, y), line, font=font, fill=(255, 255, 255))
        y += line_h
    draw.text((margin, area_top - 40), f"{label} - placeholder visual", font=_font(30), fill=(235, 235, 235))
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, "PNG")


def render_end_card(path: Path, title: str, cta: str, disclosure: str, hue: float, spec: VideoSpec) -> None:
    """Render a dedicated end card with title, CTA and AI-disclosure footer."""
    img = _gradient(spec.width, spec.height, hue)
    draw = ImageDraw.Draw(img)
    margin = 90
    area_top, area_bottom = spec.safe_top_px + 60, spec.height - spec.safe_bottom_px - 60

    # Institution header at top
    header = title or "Agentic AI Lab"
    draw.text((margin, area_top), header, font=_font(42), fill=(235, 235, 235))

    # Prominent call to action in center
    cta_text = cta or "Come and build with us."
    font_cta = _font(64)
    lines = _wrap(draw, cta_text, font_cta, spec.width - 2 * margin)
    line_h = int(64 * 1.3)
    y = (area_top + area_bottom - len(lines) * line_h) // 2
    for line in lines:
        w = draw.textlength(line, font=font_cta)
        draw.text(((spec.width - w) / 2, y), line, font=font_cta, fill=(255, 255, 255))
        y += line_h

    # Legal / AI-disclosure line near bottom (above safe bottom)
    if disclosure:
        font_disc = _font(28)
        w_disc = draw.textlength(disclosure, font=font_disc)
        draw.text(((spec.width - w_disc) / 2, area_bottom - 20), disclosure, font=font_disc, fill=(220, 220, 220))

    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, "PNG")


def write_manifest_csv(manifest: AssetManifest, csv_path: Path) -> None:
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    with csv_path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=CSV_FIELDS)
        w.writeheader()
        for a in manifest.assets:
            w.writerow({"asset_path": a.path or "", "source": a.source, "licence_status": a.licence,
                        "intended_use": a.intended_use, "asset_id": a.asset_id, "kind": a.kind, "status": a.status})


def run(inp: AssetGenInput, llm=None, log=None) -> AssetManifest:
    root = Path(inp.root)
    folder = root / "assets" / "generated" / inp.brief.brief_id
    if folder.exists():
        shutil.rmtree(folder)           # drop stale cards from earlier attempts
    folder.mkdir(parents=True, exist_ok=True)

    records: list[AssetRecord] = []
    for i, shot in enumerate(inp.storyboard.shots):
        hue = ((inp.seed * 37 + i * 47) % 360) / 360
        path = folder / f"{shot.shot_id}.png"
        caption = limit_caption(shot.on_screen_text, 80)
        render_card(path, shot.shot_id, caption, hue, inp.spec)
        records.append(AssetRecord(
            asset_id=f"img_{shot.shot_id}", kind="image", shot_id=shot.shot_id,
            path=path.relative_to(root).as_posix(), status="generated", source=SOURCE, licence=LICENCE,
            intended_use=f"placeholder background for {shot.shot_id}", placeholder=True))
    records += [
        AssetRecord(asset_id="voiceover", kind="voiceover", path=f"assets/generated/{inp.brief.brief_id}/voiceover.mp3",
                    status="planned", source="text-to-speech (Milestone C)", licence="to be recorded when generated",
                    intended_use="narration track"),
        AssetRecord(asset_id="subtitles", kind="subtitles", path="outputs/subtitles.srt", status="planned",
                    source="derived from the script and measured audio timing (Milestone C)",
                    licence="original", intended_use="burned-in captions and .srt file"),
        AssetRecord(asset_id="music", kind="music", path=None, status="omitted",
                    source="none", licence="omitted: no licensed or original track available",
                    intended_use="background music (not used)")]
    manifest = AssetManifest(
        brief_id=inp.brief.brief_id, assets=records,
        notes=["Only the image cards exist on disk. Voice-over and subtitles are planned for Milestone C; "
               "no video has been rendered."])
    write_manifest_csv(manifest, root / "assets" / "manifest.csv")
    return manifest
